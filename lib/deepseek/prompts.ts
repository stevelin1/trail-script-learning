export function buildLearningMaterialUserPrompt(japaneseText: string, characterName?: string): string {
  return `
请对以下日语台词进行详细的、教学级分析。

${characterName ? `角色：${characterName}` : ''}

台词：${japaneseText}

请确保：
1. 只分析值得学习的词汇（跳过基础词汇如助词、常见动词等）
2. reading字段仅包含假名读音（无音调数字），pitch字段仅包含音调数字标记（如①），切勿重复
3. 如果是动词，列出辞书形・ます形・た形
4. 文法点选择真正有教学价值的内容
5. 提供直译和自然中文翻译
6. 整句假名读音标注所有汉字
7. 只输出JSON格式，不要包含其他文字

严格按照system prompt中定义的JSON格式输出。
`;
}
